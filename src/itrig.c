void itrig_trig(unsigned theta_bin, int32_t *cos1024, int32_t *sin1024)
{
    if (theta_bin >= ITRIG_BINS) {
        *cos1024 = 0;
        *sin1024 = 0;
        return;
    }
    *cos1024 = ITRIG_COS1024[theta_bin];
    *sin1024 = ITRIG_SIN1024[theta_bin];
}

const int16_t *itrig_cos(void)
{
    return ITRIG_COS1024;
}

const int16_t *itrig_sin(void)
{
    return ITRIG_SIN1024;
}
